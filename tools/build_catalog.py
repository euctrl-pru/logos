#!/usr/bin/env python3
"""Generate CATALOG.md, gallery/index.html and each entity's house-style README and tokens."""
import argparse
import html
import json
import re
import sys
from pathlib import Path
from urllib.parse import quote

REPO = Path(__file__).resolve().parent.parent
GROUPS = [
    ("eurocontrol", "EUROCONTROL"),
    ("european", "European"),
    ("international", "International"),
    ("state", "States"),
]
GROUP_ORDER = {k: i for i, (k, _) in enumerate(GROUPS)}
UNKNOWN = "unknown"


def load_entities(root: Path):
    """Return sorted (entity_dir, entity) pairs for every dir with an entity.json."""
    found = []
    for path in (root / "stakeholders").rglob("entity.json"):
        ent = json.loads(path.read_text(encoding="utf-8"))
        found.append((path.parent, ent))
    found.sort(key=lambda p: (GROUP_ORDER.get(p[1].get("group"), 99),
                              p[1].get("country") or "", p[1].get("id") or ""))
    return found


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def _yes(flag):
    return "yes" if flag else "no"


def _link(root, entity_dir):
    rel = entity_dir.relative_to(root).as_posix()
    return quote(rel) + "/"


def current_assets(ent):
    return [a for a in ent.get("assets") or [] if not a.get("superseded")]


def render_row(root, entity_dir, ent):
    assets = current_assets(ent)
    light = any(a.get("background") == "light" for a in assets)
    dark = any(a.get("background") == "dark" for a in assets)
    transparent = any(a.get("transparent") for a in assets)
    name = f"[{_cell(ent.get('name', ent['id']))}]({_link(root, entity_dir)})"
    cells = [name, f"`{ent['id']}`", ent.get("status", UNKNOWN),
             _yes(light), _yes(dark), _yes(transparent), str(len(assets))]
    return "| " + " | ".join(cells) + " |"


TABLE_HEAD = ["| Entity | Id | Status | light | dark | transparent | Assets |",
              "|---|---|---|---|---|---|---|"]


def render_catalog(root: Path) -> str:
    entities = load_entities(root)
    out = ["# Catalog", "",
           "Generated by `tools/build_catalog.py`. Do not edit by hand.", ""]
    for key, title in GROUPS:
        members = [(d, e) for d, e in entities if e.get("group") == key]
        if not members:
            continue
        out += [f"## {title}", ""]
        if key == "state":
            countries = []
            for d, e in members:
                c = e.get("country") or d.parent.name
                if not countries or countries[-1][0] != c:
                    countries.append((c, []))
                countries[-1][1].append((d, e))
            for country, rows in countries:
                out += [f"### {country}", ""] + TABLE_HEAD
                out += [render_row(root, d, e) for d, e in rows] + [""]
        else:
            out += TABLE_HEAD + [render_row(root, d, e) for d, e in members] + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def _val(v):
    return UNKNOWN if v is None or v == "" else str(v)


def _evidence(item):
    return f"{_val(item.get('evidence'))} ({_val(item.get('source_url'))})"


def render_colors(style):
    colors = style.get("colors") or []
    if not colors:
        return ["No colours recorded.", ""]
    out = ["| Name | Hex | RGB | CMYK | Role | Evidence |", "|---|---|---|---|---|---|"]
    for c in colors:
        cells = [c.get("name"), c.get("hex"), c.get("rgb"), c.get("cmyk"),
                 c.get("role")]
        out.append("| " + " | ".join(_cell(_val(x)) for x in cells)
                   + " | " + _cell(_evidence(c)) + " |")
    return out + [""]


def render_typography(style):
    fonts = style.get("typography") or []
    if not fonts:
        return ["No typography recorded.", ""]
    out = ["| Family | Role | Fallbacks | Evidence |", "|---|---|---|---|"]
    for f in fonts:
        fb = ", ".join(f.get("fallbacks") or []) or None
        cells = [f.get("family"), f.get("role"), fb]
        out.append("| " + " | ".join(_cell(_val(x)) for x in cells)
                   + " | " + _cell(_evidence(f)) + " |")
    return out + [""]


def render_usage(style):
    usage = style.get("logo_usage") or {}
    keys = ("clear_space", "min_size", "background_rules", "misuse")
    return [f"- {k.replace('_', ' ')}: {_val(usage.get(k))}" for k in keys] + [""]


def render_sources(style):
    out = []
    for label, key in (("Current sources", "current_sources"),
                       ("Previous sources", "previous_sources")):
        items = style.get(key) or []
        out += [f"## {label}", ""]
        if not items:
            out += ["None recorded.", ""]
            continue
        for s in items:
            line = f"- {s.get('url')} ({_val(s.get('kind'))}, {_val(s.get('version_label'))}, retrieved {_val(s.get('retrieved'))})"
            if key == "previous_sources":
                line += f", superseded {_val(s.get('superseded_on'))}: {_val(s.get('change_summary'))}"
            out.append(line)
        out.append("")
    return out


def render_style_readme(style: dict, entity: dict) -> str:
    name = entity.get("name", entity.get("id"))
    out = [f"# {name} house style", "",
           "Generated by `tools/build_catalog.py`. Do not edit by hand.", "",
           f"Status: {_val(style.get('status'))}. Last checked: {_val(style.get('last_checked'))}.", ""]
    if style.get("status") == "none":
        out += ["No public house style found.", ""]
    else:
        out += ["## Colours", ""] + render_colors(style)
        out += ["## Typography", ""] + render_typography(style)
        out += ["## Logo usage", ""] + render_usage(style)
    out += render_sources(style)
    if style.get("notes"):
        out += ["## Notes", "", str(style["notes"]), ""]
    return "\n".join(out).rstrip("\n") + "\n"


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", str(text).lower()).strip("-")


def build_tokens(style: dict, entity: dict) -> dict:
    """Recorded colours and fonts keyed by kebab-case name; unnamed or null values are omitted."""
    colors, fonts = {}, {}
    for c in style.get("colors") or []:
        key = slugify(c.get("name") or "")
        if key and c.get("hex"):
            colors.setdefault(key, c["hex"])
    for f in style.get("typography") or []:
        key = slugify(f.get("role") or "")
        if key and f.get("family"):
            fonts.setdefault(key, ", ".join([f["family"]] + list(f.get("fallbacks") or [])))
    return {"id": entity["id"], "colors": colors, "fonts": fonts}


def render_tokens_json(tokens: dict) -> str:
    return json.dumps(tokens, indent=2, ensure_ascii=False) + "\n"


def render_tokens_css(tokens: dict) -> str:
    eid = slugify(tokens["id"])
    lines = [f"  --{eid}-color-{k}: {v};" for k, v in tokens["colors"].items()]
    lines += [f"  --{eid}-font-{k}: {v};" for k, v in tokens["fonts"].items()]
    return "\n".join([":root {"] + lines + ["}"]) + "\n"


GALLERY_CSS = """body{font:14px/1.4 system-ui,sans-serif;margin:0;padding:16px;background:#fff;color:#111}
h1{font-size:1.4em}h2{font-size:1.1em;margin:1.5em 0 .5em}
.row{display:flex;flex-wrap:wrap;gap:12px;margin-bottom:12px}
figure{margin:0}figcaption{font-size:12px;color:#555;max-width:200px;overflow-wrap:anywhere}
.tile{display:flex;align-items:center;justify-content:center;width:200px;height:120px;border:1px solid #ccc;box-sizing:border-box}
.tile img{max-width:90%;max-height:90%}
.light{background:#fff}.dark{background:#1a1a1a}"""


def render_gallery(root: Path) -> str:
    out = ["<!doctype html>", '<html lang="en">', "<head>", '<meta charset="utf-8">',
           '<meta name="viewport" content="width=device-width, initial-scale=1">',
           "<title>Logo gallery</title>", f"<style>\n{GALLERY_CSS}\n</style>", "</head>", "<body>",
           "<h1>Logo gallery</h1>",
           "<p>Generated by <code>tools/build_catalog.py</code>. Do not edit by hand.</p>"]
    for d, ent in load_entities(root):
        assets = current_assets(ent)
        title = html.escape(f"{ent.get('name', ent['id'])} ({ent['id']})")
        out.append(f"<section><h2>{title}</h2>")
        if not assets:
            out.append("<p>No logos recorded.</p>")
        for a in assets:
            rel = (d / "logos").relative_to(root).as_posix() + "/" + a["file"]
            src = "../" + quote(rel)
            alt = html.escape(f"{ent['id']} {a['file']}", quote=True)
            cap = html.escape(a["file"])
            out.append('<div class="row">')
            for mode in ("light", "dark"):
                out.append(f'<figure><div class="tile {mode}"><img src="{src}" alt="{alt}" loading="lazy"></div>'
                           f"<figcaption>{cap} on {mode}</figcaption></figure>")
            out.append("</div>")
        out.append("</section>")
    return "\n".join(out + ["</body>", "</html>"]) + "\n"


def generated_files(root: Path) -> dict:
    files = {root / "CATALOG.md": render_catalog(root),
             root / "gallery" / "index.html": render_gallery(root)}
    for d, ent in load_entities(root):
        sp = d / "house-style" / "style.json"
        if not sp.exists():
            continue
        style = json.loads(sp.read_text(encoding="utf-8"))
        files[d / "house-style" / "README.md"] = render_style_readme(style, ent)
        tokens = build_tokens(style, ent)
        files[d / "house-style" / "tokens.json"] = render_tokens_json(tokens)
        files[d / "house-style" / "tokens.css"] = render_tokens_css(tokens)
    return files


def main(check: bool = False, root: Path | None = None) -> int:
    root = Path(root) if root else REPO
    stale = 0
    for path, text in generated_files(root).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            print(f"stale: {path.relative_to(root)}", file=sys.stderr)
            stale = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    return stale


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated file is stale")
    sys.exit(main(check=ap.parse_args().check))
